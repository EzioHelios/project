async def import_real_company_package(
    session: AsyncSession,
    package_dir: str | Path,
    *,
    dry_run: bool = False,
) -> RealCompanyPackageImportResult:
    """Import one standardized enterprise validation package into tenant-scoped tables.

    The package must be generated by ``tools/standardize_verification_packages.py`` and point at
    ``docs/评价方案/real_company_standardized_data/enterprises/<enterprise_code>``.
    """

    root = Path(package_dir).expanduser().resolve()
    datasets = _load_package_datasets(root)
    return await import_real_company_datasets(session, datasets, package_root=root, dry_run=dry_run)


async def import_real_company_datasets(
    session: AsyncSession,
    datasets: dict[str, list[dict[str, str]]],
    *,
    package_root: str | Path,
    dry_run: bool = False,
    evidence_archive_root: str | Path | None = None,
) -> RealCompanyPackageImportResult:
    """Import already-normalized enterprise datasets into tenant-scoped tables."""

    root = Path(package_root).expanduser().resolve()
    profile = _single_required(datasets, "enterprise_profiles")
    enterprise_code = _text(profile.get("enterprise_code"))
    tenant_slug = _text(profile.get("tenant_slug"))
    enterprise_name = _text(profile.get("enterprise_name"))
    if not enterprise_code or not tenant_slug or not enterprise_name:
        msg = f"企业包缺少 enterprise_code / tenant_slug / enterprise_name: {root}"
        raise ValueError(msg)

    source_name = f"{IMPORT_SOURCE_PREFIX}:{enterprise_code}"
    marker = f"{PACKAGE_MARKER_PREFIX}{enterprise_code}]"
    raw_package_root = Path(_or(profile.get("package_root"), root)).expanduser()
    resolved_evidence_archive_root = (
        Path(evidence_archive_root).expanduser().resolve()
        if evidence_archive_root is not None
        else root.parents[1] / "evidence_archive" / enterprise_code
        if len(root.parents) > 1
        else root / "evidence_archive"
    )
    session.info[TENANT_BYPASS_SESSION_KEY] = True
    await session.execute(text("select set_config('app.tenant_bypass', 'true', true)"))

    result = RealCompanyPackageImportResult(
        enterprise_code=enterprise_code,
        tenant_slug=tenant_slug,
        team_id="",
        dry_run=dry_run,
    )

    team_id = await _upsert_team(session, tenant_slug=tenant_slug, enterprise_name=enterprise_name, root=root)
    result.team_id = str(team_id)

    context: dict[str, dict[str, Any]] = {
        "organizations": {},
        "periods": {},
        "boundaries": {},
        "products": {},
        "studies": {},
        "stages": {},
        "suppliers": {},
        "tasks": {},
        "batches": {},
        "projects": {},
    }

    await _import_emission_factors(session, datasets, result)
    await _import_reporting_scope(session, datasets, team_id, source_name, marker, context, result)
    await _import_production_and_energy(
        session,
        datasets,
        team_id,
        marker,
        context,
        result,
        raw_package_root,
        resolved_evidence_archive_root,
    )
    await _import_product_footprint(session, datasets, team_id, source_name, marker, context, result)
    await _import_supply_chain(session, datasets, team_id, source_name, marker, context, result)
    await _import_carbon_accounting(session, datasets, team_id, source_name, marker, context, result)
    await _import_verification(
        session,
        datasets,
        team_id,
        source_name,
        marker,
        context,
        result,
        raw_package_root,
        resolved_evidence_archive_root,
    )
    await _import_carbon_assets(session, datasets, team_id, source_name, marker, context, result)
    _collect_source_missing_pages(datasets, result)

    if dry_run:
        await session.rollback()
    else:
        await session.commit()
        session.info.pop(TENANT_BYPASS_SESSION_KEY, None)
        session.info[TENANT_ID_SESSION_KEY] = UUID(str(team_id))
        for billing_month in sorted(
            {_billing_month(row.get("billing_month")) for row in datasets["scope2_electricity_bills"]}
        ):
            await reconcile_scope2_electricity(session, billing_month)
    return result


async def import_real_company_packages(
    session: AsyncSession,
    packages_root: str | Path,
    *,
    dry_run: bool = False,
) -> list[RealCompanyPackageImportResult]:
    """Import one package directory or every enterprise package under an enterprises root."""

    root = Path(packages_root).expanduser().resolve()
    package_dirs = (
        sorted(path for path in root.iterdir() if path.is_dir() and (path / "00_tenant").exists())
        if (root / "honda").exists()
        else [root]
    )
    return [await import_real_company_package(session, package_dir, dry_run=dry_run) for package_dir in package_dirs]


def default_real_company_packages_root() -> Path:
    """Return the fixed repository-local root for standardized validation packages."""

    return DEFAULT_REAL_COMPANY_PACKAGES_ROOT.expanduser().resolve()


def resolve_real_company_package_dir(enterprise_code: str, *, packages_root: str | Path | None = None) -> Path:
    """Resolve an enterprise code to a known package directory under the fixed package root.

    This intentionally does not accept arbitrary paths from API callers. Operators select one of the
    standardized enterprise package codes, and the server maps it to the repository-local staging root.
    """

    normalized_code = _safe_enterprise_code(enterprise_code)
    root = (
        Path(packages_root).expanduser().resolve()
        if packages_root is not None
        else default_real_company_packages_root()
    )
    package_dir = (root / normalized_code).resolve()
    try:
        package_dir.relative_to(root)
    except ValueError as exc:
        msg = f"企业包路径越界: {enterprise_code}"
        raise ValueError(msg) from exc
    if not package_dir.is_dir() or not (package_dir / "00_tenant").is_dir():
        msg = f"未找到企业标准资料包: {normalized_code}"
        raise ValueError(msg)
    return package_dir


def list_real_company_package_summaries(*, packages_root: str | Path | None = None) -> list[RealCompanyPackageSummary]:
    """List standardized enterprise validation packages with source row and gap counts."""

    root = (
        Path(packages_root).expanduser().resolve()
        if packages_root is not None
        else default_real_company_packages_root()
    )
    if not root.is_dir():
        return []
    summaries: list[RealCompanyPackageSummary] = []
    for package_dir in sorted(path for path in root.iterdir() if path.is_dir() and (path / "00_tenant").is_dir()):
        try:
            summaries.append(summarize_real_company_package(package_dir))
        except ValueError:
            continue
    return summaries


def summarize_real_company_package(package_dir: str | Path) -> RealCompanyPackageSummary:
    """Build a read-only summary for one standardized package."""

    root = Path(package_dir).expanduser().resolve()
    datasets = _load_package_datasets(root)
    profile = _single_required(datasets, "enterprise_profiles")
    enterprise_code = _text(profile.get("enterprise_code"))
    tenant_slug = _text(profile.get("tenant_slug"))
    enterprise_name = _text(profile.get("enterprise_name"))
    if not enterprise_code or not tenant_slug or not enterprise_name:
        msg = f"企业包缺少 enterprise_code / tenant_slug / enterprise_name: {root}"
        raise ValueError(msg)

    page_status_counts: dict[str, int] = {}
    missing_datasets: set[str] = set()
    for row in datasets["page_upload_validation_checklist"]:
        status = _text(row.get("completeness_status")) or "unknown"
        page_status_counts[status] = page_status_counts.get(status, 0) + 1
        for item in (_text(row.get("missing_datasets")) or "").split(","):
            normalized = item.strip()
            if normalized:
                missing_datasets.add(normalized)

    return RealCompanyPackageSummary(
        enterprise_code=enterprise_code,
        enterprise_name=enterprise_name,
        tenant_slug=tenant_slug,
        package_path=_repo_relative_path(root),
        dataset_rows={name: len(rows) for name, rows in datasets.items()},
        page_status_counts=page_status_counts,
        missing_datasets=sorted(missing_datasets),
    )


def _safe_enterprise_code(value: str) -> str:
    normalized = value.strip().lower()
    if not re.fullmatch(r"[a-z0-9_-]+", normalized):
        msg = f"非法企业包编码: {value}"
        raise ValueError(msg)
    return normalized


async def _upsert_team(session: AsyncSession, *, tenant_slug: str, enterprise_name: str, root: Path) -> str:
    row = await session.execute(text("select id from team where slug = :slug"), {"slug": tenant_slug})
    existing = row.scalar_one_or_none()
    if existing:
        await session.execute(
            text(
                """
                update team
                set name = :name,
                    description = :description,
                    is_active = true,
                    updated_at = now()
                where id = :id
                """
            ),
            {"id": existing, "name": enterprise_name, "description": f"真实企业资料包验收租户: {root}"},
        )
        return str(existing)
    team_id = str(uuid4())
    await session.execute(
        text(
            """
            insert into team (id, slug, name, description, is_active, created_at, updated_at)
            values (:id, :slug, :name, :description, true, now(), now())
            """
        ),
        {"id": team_id, "slug": tenant_slug, "name": enterprise_name, "description": f"真实企业资料包验收租户: {root}"},
    )
    return team_id


async def _import_emission_factors(
    session: AsyncSession,
    datasets: dict[str, list[dict[str, str]]],
    result: RealCompanyPackageImportResult,
) -> None:
    imported = 0
    updated = 0
    for row in datasets["emission_factors"]:
        scope = _short_code(row.get("scope"), "", 10)
        category = _short_code(row.get("category"), "", 20)
        sub_category = _short_code(row.get("sub_category"), "", 64)
        unit = _short_code(row.get("unit"), "", 20)
        year = _int(row.get("year"), 0)
        if not scope or not category or not sub_category or not unit or year <= 0:
            result.skipped["emission_factors"] = result.skipped.get("emission_factors", 0) + 1
            continue

        existing = (
            await session.execute(
                text(
                    """
                    select id
                    from dataapp_emissionfactor
                    where scope = :scope
                      and category = :category
                      and sub_category = :sub_category
                      and unit = :unit
                      and year = :year
                    limit 1
                    """
                ),
                {"scope": scope, "category": category, "sub_category": sub_category, "unit": unit, "year": year},
            )
        ).scalar_one_or_none()
        values = {
            "scope": scope,
            "category": category,
            "sub_category": sub_category,
            "unit": unit,
            "factor_value": _decimal(row.get("factor_value")),
            "factor_unit": _short_code(row.get("factor_unit"), "kgCO2e", 32),
            "year": year,
            "source": _short_code(row.get("source"), "real_company_package", 128),
            "is_active": _bool(row.get("is_active"), default=True),
            "note": row.get("note"),
            "source_system": _short_code(row.get("source_system"), "real_company_package", 64),
            "source_snapshot_id": _short_code(row.get("source_snapshot_id"), "", 64) or None,
            "projection_status": _short_code(row.get("projection_status"), "manual", 24),
            "review_status": _short_code(row.get("review_status"), "approved", 24),
        }
        if existing is None:
            values["id"] = await _next_bigint_id(session, "dataapp_emissionfactor")
            await session.execute(
                text(
                    """
                    insert into dataapp_emissionfactor (
                        id, scope, category, sub_category, unit, factor_value, factor_unit, year, source, is_active,
                        note, source_system, source_snapshot_id, projection_status, review_status, created_at, updated_at
                    )
                    values (
                        :id, :scope, :category, :sub_category, :unit, :factor_value, :factor_unit, :year, :source, :is_active,
                        :note, :source_system, :source_snapshot_id, :projection_status, :review_status, now(), now()
                    )
                    """
                ),
                values,
            )
            imported += 1
        else:
            await session.execute(
                text(
                    """
                    update dataapp_emissionfactor
                    set factor_value = :factor_value,
                        factor_unit = :factor_unit,
                        source = :source,
                        is_active = :is_active,
                        note = :note,
                        source_system = :source_system,
                        source_snapshot_id = :source_snapshot_id,
                        projection_status = :projection_status,
                        review_status = :review_status,
                        updated_at = now()
                    where id = :id
                    """
                ),
                {**values, "id": existing},
            )
            updated += 1
    result.imported["emission_factors"] = imported
    if updated:
        result.imported["emission_factors_updated"] = updated


async def _import_reporting_scope(
    session: AsyncSession,
    datasets: dict[str, list[dict[str, str]]],
    team_id: str,
    source_name: str,
    marker: str,
    context: dict[str, dict[str, Any]],
    result: RealCompanyPackageImportResult,
) -> None:
    for row in datasets["reporting_organizations"]:
        org_id = await _upsert_id(
            session,
            "carbon_reporting_organization",
            ["team_id", "code"],
            {
                "team_id": team_id,
                "code": row["code"],
                "name": row["name"],
                "organization_type": _or(row.get("organization_type"), "enterprise"),
                "control_method": _or(row.get("control_method"), "operational_control"),
                "status": "active",
                "source_name": source_name,
                "standard_code": row.get("standard_code"),
                "remark": _mark(marker, f"source={row.get('source_name', '')}"),
            },
        )
        context["organizations"][row["code"]] = org_id
    result.imported["reporting_organizations"] = len(datasets["reporting_organizations"])

    for row in datasets["reporting_periods"]:
        org_id = context["organizations"].get(row["reporting_org_code"])
        if not org_id:
            result.skipped["reporting_periods"] = result.skipped.get("reporting_periods", 0) + 1
            continue
        period_id = await _upsert_id(
            session,
            "carbon_reporting_period",
            ["team_id", "reporting_org_id", "code"],
            {
                "team_id": team_id,
                "reporting_org_id": org_id,
                "code": row["period_code"],
                "name": row["name"],
                "period_type": _or(row.get("period_type"), "annual"),
                "period_start": _date(row.get("period_start")),
                "period_end": _date(row.get("period_end")),
                "status": _or(row.get("status"), "draft"),
                "source_name": source_name,
                "remark": _mark(marker, f"source={row.get('source_name', '')}"),
            },
        )
        context["periods"][row["period_code"]] = period_id
    result.imported["reporting_periods"] = len(datasets["reporting_periods"]) - result.skipped.get(
        "reporting_periods", 0
    )

    for row in datasets["organization_boundaries"]:
        org_id = context["organizations"].get(row["reporting_org_code"])
        period_id = context["periods"].get(row["period_code"])
        if not org_id or not period_id:
            result.skipped["organization_boundaries"] = result.skipped.get("organization_boundaries", 0) + 1
            continue
        boundary_id = await _upsert_id(
            session,
            "carbon_organization_boundary",
            ["team_id", "boundary_no"],
            {
                "team_id": team_id,
                "reporting_org_id": org_id,
                "period_id": period_id,
                "boundary_no": row["boundary_no"],
                "boundary_name": row["boundary_name"],
                "boundary_type": _or(row.get("boundary_type"), "organization"),
                "boundary_method": _or(row.get("boundary_method"), "operational_control"),
                "operational_boundary": _json(row.get("operational_boundary")),
                "version": 1,
                "status": _or(row.get("status"), "draft"),
                "source_name": source_name,
                "standard_code": row.get("standard_code"),
                "confidence_level": "source",
                "remark": _mark(marker, f"source={row.get('source_name', '')}"),
            },
        )
        context["boundaries"][row["boundary_no"]] = boundary_id
    result.imported["organization_boundaries"] = len(datasets["organization_boundaries"]) - result.skipped.get(
        "organization_boundaries", 0
    )


