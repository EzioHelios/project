def _date(value: Any) -> date:
    parsed = _optional_date(value)
    if parsed is None:
        return datetime.now(UTC).date()
    return parsed


def _optional_date(value: Any) -> date | None:
    text_value = _text(value)
    if not text_value:
        return None
    match = re.search(r"(20\d{2})[-/.年](\d{1,2})[-/.月](\d{1,2})", text_value)
    if match:
        year, month, day = (int(part) for part in match.groups())
        return date(year, month, day)
    if re.fullmatch(r"20\d{2}-\d{2}", text_value):
        year, month = (int(part) for part in text_value.split("-"))
        return date(year, month, 1)
    if re.fullmatch(r"20\d{2}", text_value):
        return date(int(text_value), 1, 1)
    return date.fromisoformat(text_value[:10])


def _datetime(value: Any) -> datetime:
    return datetime.combine(_date(value), datetime.min.time())


def _billing_month(value: Any) -> str:
    text_value = _text(value)
    match = re.search(r"(20\d{2})[-/年](\d{1,2})", text_value)
    if match:
        year, month = (int(part) for part in match.groups())
        return f"{year}-{month:02d}"
    year_match = re.search(r"(20\d{2})", text_value)
    if year_match:
        return f"{year_match.group(1)}-12"
    return "2025-12"


def _json(value: Any, default: Any | None = None) -> Any:
    text_value = _text(value)
    if not text_value:
        return default
    try:
        return json.loads(text_value)
    except json.JSONDecodeError:
        return default
